// aiJobTracker is the Node JobTracker: one single-flight slot whose state
// is served by the status endpoints and published as <prefix>_progress /
// <prefix>_done WebSocket events.
type aiJobTracker struct {
	kind, prefix string
	hub          *ws.Hub

	mu      sync.Mutex
	running bool
	cancel  context.CancelFunc
	state   map[string]any
}

func newAIJobTracker(kind, prefix string, hub *ws.Hub) *aiJobTracker {
	return &aiJobTracker{kind: kind, prefix: prefix, hub: hub, state: map[string]any{
		"kind": kind, "running": false, "stage": "idle", "progress": map[string]any{}, "startedAt": 0,
		"finishedAt": 0, "durationMs": 0, "result": nil, "error": nil, "attempts": 0, "successes": 0, "failures": 0,
	}}
}

func (t *aiJobTracker) Status() map[string]any {
	t.mu.Lock()
	defer t.mu.Unlock()
	return t.snapshotLocked()
}

func (t *aiJobTracker) snapshotLocked() map[string]any {
	out := cloneConfigValue(t.state).(map[string]any)
	out["running"] = t.running
	return out
}

func (t *aiJobTracker) Running() bool {
	t.mu.Lock()
	defer t.mu.Unlock()
	return t.running
}

// Start claims the slot, runs begin synchronously, then run in the
// background as an app maintenance job (joined on shutdown). It returns
// the snapshot, errAIJobRunning or errAIStopping.
func (t *aiJobTracker) Start(a *App, begin func(), run func(context.Context, func(map[string]any)) (map[string]any, error)) (map[string]any, error) {
	done, ok := a.beginMaintenance()
	if !ok {
		return nil, errAIStopping
	}
	t.mu.Lock()
	if t.running {
		snapshot := t.snapshotLocked()
		t.mu.Unlock()
		done()
		return snapshot, errAIJobRunning
	}
	ctx, cancel := context.WithCancel(a.ctx)
	t.running, t.cancel = true, cancel
	started := time.Now()
	t.state["stage"], t.state["progress"], t.state["startedAt"] = "starting", map[string]any{}, started.UnixMilli()
	t.state["finishedAt"], t.state["durationMs"], t.state["error"] = 0, 0, nil
	t.state["attempts"] = jobCount(t.state["attempts"]) + 1
	if begin != nil {
		begin()
	}
	snapshot := t.snapshotLocked()
	t.mu.Unlock()
	t.hub.Broadcast(ws.Event{Type: t.prefix + "_progress", Flat: true, Payload: snapshot})
	go func() {
		defer done()
		defer cancel()
		progress := func(p map[string]any) {
			t.mu.Lock()
			if !t.running {
				t.mu.Unlock()
				return
			}
			if stage := toString(p["stage"]); stage != "" {
				t.state["stage"] = stage
			}
			merged, _ := t.state["progress"].(map[string]any)
			for k, v := range p {
				merged[k] = v
			}
			payload := t.snapshotLocked()
			t.mu.Unlock()
			for k, v := range p {
				payload[k] = v
			}
			t.hub.Broadcast(ws.Event{Type: t.prefix + "_progress", Flat: true, Payload: payload})
		}
		result, err := run(ctx, progress)
		duration := time.Since(started).Milliseconds()
		payload := map[string]any{}
		t.mu.Lock()
		t.running, t.cancel = false, nil
		if progress, ok := t.state["progress"].(map[string]any); ok {
			delete(progress, "running")
		}
		t.state["finishedAt"], t.state["durationMs"] = time.Now().UnixMilli(), duration
		if err != nil {
			t.state["stage"], t.state["error"] = "error", err.Error()
			t.state["failures"] = jobCount(t.state["failures"]) + 1
			payload["error"] = err.Error()
		} else {
			t.state["stage"], t.state["result"] = "done", result
			t.state["successes"] = jobCount(t.state["successes"]) + 1
			for k, v := range result {
				payload[k] = v
			}
		}
		t.mu.Unlock()
		payload["durationMs"], payload["kind"] = duration, t.kind
		t.hub.Broadcast(ws.Event{Type: t.prefix + "_done", Flat: true, Payload: payload})
	}()
	return snapshot, nil
}

// Cancel aborts the running job; false when nothing runs.
func (t *aiJobTracker) Cancel() bool {
	t.mu.Lock()
	defer t.mu.Unlock()
	if !t.running || t.cancel == nil {
		return false
	}
	t.cancel()
	return true
}
