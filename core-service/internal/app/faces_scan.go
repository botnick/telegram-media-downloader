// Face detection and clustering, ported from src/core/ai/scan-runner.js and
// src/core/ai/index.js of the Node app. Rows, columns and blobs are the
// ones Node wrote, so faces found by 2.x and by this server cluster
// together:
//
//   - faces(download_id, x, y, w, h, embedding float32-LE blob,
//     quality_score, exif_oriented, frame_time_sec), person_id from the
//     clustering pass;
//   - people(label, embedding_centroid float32-LE blob, face_count, …),
//     regenerated by every clustering pass, labels carried over to the
//     new cluster whose centroid is closest (within labelMatchEps);
//   - downloads.ai_indexed_at, stamped once the sidecar answered for a row.

const (
	facesMaxItemAttempts  = 3
	facesMaxSkippedFiles  = 100
	facesClusterLoadChunk = 2000
	facesClusterWrite     = 5000
	facesQueueCap         = 200
	facesProgressEvery    = 500 * time.Millisecond
)

var (
	errAIJobRunning = errors.New("job already running")
	errAIStopping   = errors.New("server is stopping")
)

// facesScanState is getScanState('faces') of the Node scan runner.
type facesScanState struct {
	Running           bool    `json:"running"`
	Scanned           int     `json:"scanned"`
	Total             int     `json:"total"`
	StartedAt         *int64  `json:"startedAt"`
	FinishedAt        *int64  `json:"finishedAt"`
	Error             *string `json:"error"`
	Phase             string  `json:"phase"`
	FaceCount         int     `json:"faceCount"`
	PeopleCount       int     `json:"peopleCount"`
	NoiseFaces        int     `json:"noiseFaces"`
	ClusterProgress   float64 `json:"clusterProgress"`
	WaitingForSidecar bool    `json:"waitingForSidecar"`
}

func (s facesScanState) payload() map[string]any {
	deref := func(p any) any {
		switch v := p.(type) {
		case *int64:
			if v != nil {
				return *v
			}
		case *string:
			if v != nil {
				return *v
			}
		}
		return nil
	}
	return map[string]any{
		"running": s.Running, "scanned": s.Scanned, "total": s.Total, "startedAt": deref(s.StartedAt),
		"finishedAt": deref(s.FinishedAt), "error": deref(s.Error), "phase": s.Phase, "faceCount": s.FaceCount,
		"peopleCount": s.PeopleCount, "noiseFaces": s.NoiseFaces, "clusterProgress": s.ClusterProgress,
		"waitingForSidecar": s.WaitingForSidecar,
	}
}

type facesService struct {
	app     *App
	client  *facesClient
	people  *aiJobTracker // ai_people_* events, the face scan
	quality *aiJobTracker // quality_backfill_* events

	mu       sync.Mutex
	scan     facesScanState
	lastSent time.Time

	queueMu    sync.Mutex
	realtime   []int64
	backfill   []int64
	wake       chan struct{}
	configWake chan struct{}
}

func newFacesService(a *App) *facesService {
	return &facesService{
		app:        a,
		client:     newFacesClient(),
		people:     newAIJobTracker("aiPeople", "ai_people", a.hub),
		quality:    newAIJobTracker("qualityBackfill", "quality_backfill", a.hub),
		scan:       facesScanState{Phase: "A"},
		wake:       make(chan struct{}, 1),
		configWake: make(chan struct{}, 1),
	}
}

func (s *facesService) logf(format string, args ...any) {
	if s.app.output != nil {
		fmt.Fprintf(s.app.output, "[ai-faces] "+format+"\n", args...)
	}
}

// settings loads advanced.ai and points the client at the configured sidecar.
func (s *facesService) settings(ctx context.Context) (facesSettings, error) {
	cfg, err := s.app.facesSettings(ctx)
	if err != nil {
		return cfg, err
	}
	s.client.configure(cfg)
	return cfg, nil
}

func (s *facesService) scanState() facesScanState {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.scan
}

func (s *facesService) scanRunning() bool { return s.scanState().Running }

// updateScan mutates the scan state and publishes it, at most every
// 500 ms unless forced (phase changes, start, end).
func (s *facesService) updateScan(force bool, progress func(map[string]any), fn func(*facesScanState)) {
	s.mu.Lock()
	fn(&s.scan)
	snapshot := s.scan
	send := force || time.Since(s.lastSent) >= facesProgressEvery
	if send {
		s.lastSent = time.Now()
	}
	s.mu.Unlock()
	if send && progress != nil {
		progress(snapshot.payload())
	}
}

// startScan claims the face-scan slot. detect=false (re-cluster without a
// sidecar) skips Phase A and only re-runs the clustering.
func (s *facesService) startScan(cfg facesSettings, detect bool) error {
	_, err := s.people.Start(s.app, func() {
		now := nowMillis()
		s.mu.Lock()
		s.scan = facesScanState{Running: true, StartedAt: &now, Phase: "A"}
		s.lastSent = time.Time{}
		s.mu.Unlock()
	}, func(ctx context.Context, progress func(map[string]any)) (map[string]any, error) {
		s.markPending(true)
		err := s.runScan(ctx, cfg, detect, progress)
		if s.app.ctx.Err() == nil {
			// A scan interrupted by shutdown stays marked and resumes on boot.
			s.markPending(false)
		}
		var final facesScanState
		s.updateScan(true, progress, func(st *facesScanState) {
			now := nowMillis()
			st.Running, st.WaitingForSidecar, st.FinishedAt = false, false, &now
			if err != nil {
				msg := err.Error()
				st.Error = &msg
			}
			final = *st
		})
		if err != nil {
			s.logf("faces scan crashed: %v", err)
			return nil, err
		}
		return final.payload(), nil
	})
	return err
}

func (s *facesService) cancelScan() bool { return s.people.Cancel() }

// facesPendingKey marks a face scan in progress (the Node auto-resume key).
const facesPendingKey = "pending_job_ai_faces"

func (s *facesService) markPending(on bool) {
	ctx := context.Background()
	var err error
	if on {
		_, err = s.app.db.Writer.ExecContext(ctx, `INSERT INTO kv(key,value,updated_at) VALUES(?,?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value,updated_at=excluded.updated_at`, facesPendingKey, fmt.Sprintf(`{"startedAt":%d}`, nowMillis()), nowMillis())
	} else {
		_, err = s.app.db.Writer.ExecContext(ctx, `DELETE FROM kv WHERE key = ?`, facesPendingKey)
	}
	if err != nil {
		s.logf("pending scan marker: %v", err)
	}
}

// resume restarts a face scan the previous process did not finish, a few
// seconds after boot, when AI is still on and a sidecar is configured.
func (s *facesService) resume() {
	s.app.launchMaintenance(func() {
		sleepCtx(s.app.ctx, 5*time.Second)
		ctx := s.app.ctx
		if ctx.Err() != nil {
			return
		}
		var raw string
		if err := s.app.db.Reader.QueryRowContext(ctx, `SELECT value FROM kv WHERE key = ?`, facesPendingKey).Scan(&raw); err != nil || raw == "" || raw == "null" {
			return
		}
		cfg, err := s.settings(ctx)
		if err != nil {
			return
		}
		if !cfg.Enabled || cfg.URL == "" {
			s.markPending(false)
			return
		}
		s.logf("resuming the interrupted faces scan")
		if err := s.startScan(cfg, true); err != nil && !errors.Is(err, errAIJobRunning) {
			s.logf("resume faces scan: %v", err)
		}
	})
}

func (s *facesService) runScan(ctx context.Context, cfg facesSettings, detect bool, progress func(map[string]any)) error {
	if detect {
		if err := s.detectPhase(ctx, cfg, progress); err != nil || ctx.Err() != nil {
			return err
		}
	}
	return s.clusterPhase(ctx, cfg, progress)
}

func sqlIn(values []string) (string, []any) {
	args := make([]any, len(values))
	for i, v := range values {
		args[i] = v
	}
	return strings.TrimSuffix(strings.Repeat("?,", len(values)), ","), args
}

type facesRow struct {
	id       int64
	path     string
	fileType string
}

// unindexed returns the oldest unscanned rows of the given types.
func (s *facesService) unindexed(ctx context.Context, types []string, limit int) ([]facesRow, error) {
	marks, args := sqlIn(types)
	args = append(args, max(1, limit))
	rows, err := s.app.db.Reader.QueryContext(ctx, `SELECT id, file_path, file_type FROM downloads
		 WHERE file_type IN (`+marks+`) AND ai_indexed_at IS NULL AND file_path NOT LIKE '%.part'
		 ORDER BY id ASC LIMIT ?`, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []facesRow
	for rows.Next() {
		var row facesRow
		var path, fileType sql.NullString
		if err := rows.Scan(&row.id, &path, &fileType); err != nil {
			return nil, err
		}
		row.path, row.fileType = path.String, fileType.String
		out = append(out, row)
	}
	return out, rows.Err()
}

func (s *facesService) countUnindexed(ctx context.Context, types []string) (int, error) {
	marks, args := sqlIn(types)
	var n int
	err := s.app.db.Reader.QueryRowContext(ctx, `SELECT COUNT(*) FROM downloads WHERE file_type IN (`+marks+`) AND ai_indexed_at IS NULL`, args...).Scan(&n)
	return n, err
}

// resolveMedia maps a stored download path to a file on disk (the Node
// _resolveAbs): absolute paths as they are, otherwise relative to the
// downloads root, then the legacy <data>/downloads.
func (a *App) resolveMedia(stored string) string {
	if stored == "" {
		return ""
	}
	if filepath.IsAbs(stored) {
		if regularFile(stored) {
			return stored
		}
	}
	rel := strings.ReplaceAll(stored, `\`, "/")
	for strings.HasPrefix(rel, "data/downloads/") {
		rel = strings.TrimPrefix(rel, "data/downloads/")
	}
	roots := []string{a.downloadsDir}
	if legacy := filepath.Join(a.dataDir, "downloads"); legacy != a.downloadsDir {
		roots = append(roots, legacy)
	}
	for _, root := range roots {
		candidate := filepath.Join(root, filepath.FromSlash(rel))
		if inside, err := filepath.Rel(root, candidate); err == nil && !strings.HasPrefix(inside, "..") && regularFile(candidate) {
			return candidate
		}
	}
	return ""
}

func regularFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

func embeddingBlob(values []float32) []byte {
	out := make([]byte, 4*len(values))
	for i, v := range values {
		binary.LittleEndian.PutUint32(out[i*4:], math.Float32bits(v))
	}
	return out
}

// persist stamps `stamp` rows and stores the detections of `results` in
// one transaction (scan-runner.js _persistDetection): a row with faces
// has its previous faces replaced; every answered row is stamped.
func (s *facesService) persist(ctx context.Context, stamp []int64, results map[int64]fileDetection) error {
	tx, err := s.app.db.Writer.BeginTx(context.WithoutCancel(ctx), nil)
	if err != nil {
		return err
	}
	defer tx.Rollback() //nolint:errcheck // no-op after Commit
	now := nowMillis()
	for _, id := range stamp {
		if _, err := tx.Exec(`UPDATE downloads SET ai_indexed_at = ? WHERE id = ?`, now, id); err != nil {
			return err
		}
	}
	for id, det := range results {
		if len(det.faces) > 0 {
			if _, err := tx.Exec(`DELETE FROM faces WHERE download_id = ?`, id); err != nil {
				return err
			}
			for _, f := range det.faces {
				var exif, frame any
				if f.ExifOriented {
					exif = 1
				}
				if f.FrameTimeSec != nil {
					frame = *f.FrameTimeSec
				}
				if _, err := tx.Exec(`INSERT INTO faces (download_id, x, y, w, h, embedding, person_id, quality_score, exif_oriented, frame_time_sec)
					VALUES (?, ?, ?, ?, ?, ?, NULL, ?, ?, ?)`, id, f.X, f.Y, f.W, f.H, embeddingBlob(f.Embedding), f.storedQuality(), exif, frame); err != nil {
					return err
				}
			}
		}
		if _, err := tx.Exec(`UPDATE downloads SET ai_indexed_at = ? WHERE id = ?`, now, id); err != nil {
			return err
		}
	}
	return tx.Commit()
}

func sleepCtx(ctx context.Context, d time.Duration) {
	if d <= 0 {
		return
	}
	timer := time.NewTimer(d)
	defer timer.Stop()
	select {
	case <-ctx.Done():
	case <-timer.C:
	}
}

// detectPhase is Phase A: every unscanned photo (and video, when enabled)
// goes to the sidecar; rows are stamped only once the sidecar answered.
func (s *facesService) detectPhase(ctx context.Context, cfg facesSettings, progress func(map[string]any)) error {
	photos, err := s.countUnindexed(ctx, cfg.ScanTypes)
	if err != nil {
		return err
	}
	videos := 0
	if cfg.ScanVideos {
		if videos, err = s.countUnindexed(ctx, []string{"video"}); err != nil {
			return err
		}
	}
	s.updateScan(true, progress, func(st *facesScanState) { st.Total = photos + videos })
	if videos > 0 {
		s.logf("faces scan: %d photos + %d videos to scan in phase A", photos, videos)
	} else {
		s.logf("faces scan: %d photos to scan in phase A", photos)
	}
	params := cfg.detectParams()

	ensureSidecar := func(why string) error {
		s.updateScan(true, progress, func(st *facesScanState) { st.WaitingForSidecar = true })
		ready := s.client.WaitReady(ctx, cfg.SidecarWait, s.logf)
		s.updateScan(true, progress, func(st *facesScanState) { st.WaitingForSidecar = false })
		if ready || ctx.Err() != nil {
			return nil
		}
		return fmt.Errorf("face sidecar unavailable (%s) — gave up after %d s. Files not scanned yet stay queued for the next scan", why, int(cfg.SidecarWait.Seconds()))
	}

	attempts := map[int64]int{}
	skipped := map[int64]bool{}
	// noteFailure returns true when the row is given up on for this run.
	// alone: the failed request carried only this file.
	noteFailure := func(row facesRow, cause error, alone bool) (bool, error) {
		var unavailable *facesUnavailableError
		if errors.As(cause, &unavailable) && unavailable.fatal {
			return false, cause
		}
		n := attempts[row.id] + 1
		if alone && unavailable != nil && unavailable.timedOut {
			n = facesMaxItemAttempts
		}
		attempts[row.id] = n
		if n < facesMaxItemAttempts {
			return false, nil
		}
		delete(attempts, row.id)
		skipped[row.id] = true
		s.logf("faces scan: skipping %s for this run after %d failed attempts (%v) — left unscanned, the next scan retries it", row.path, n, cause)
		if len(skipped) >= facesMaxSkippedFiles {
			return true, fmt.Errorf("%d files failed repeatedly — the face sidecar looks unstable; stopping the scan (nothing was marked as scanned)", len(skipped))
		}
		return true, nil
	}
	pick := func(types []string, limit int) ([]facesRow, error) {
		rows, err := s.unindexed(ctx, types, limit+len(skipped))
		if err != nil {
			return nil, err
		}
		out := rows[:0]
		for _, row := range rows {
			if !skipped[row.id] && len(out) < limit {
				out = append(out, row)
			}
		}
		return out, nil
	}

	if photos+videos > 0 && ctx.Err() == nil {
		if err := ensureSidecar("scan start"); err != nil {
			return err
		}
	}

	var statNull, statSkip, statEmpty, statFaces, statPhotos int
	nextStatLog := 200
	for ctx.Err() == nil {
		batch, err := pick(cfg.ScanTypes, cfg.BatchSize)
		if err != nil {
			return err
		}
		if len(batch) == 0 {
			break
		}
		type item struct {
			row facesRow
			abs string
		}
		var stamp []int64
		var valid []item
		missing, excluded := 0, 0
		for _, row := range batch {
			abs := s.app.resolveMedia(row.path)
			switch {
			case abs == "":
				stamp = append(stamp, row.id)
				missing++
			case cfg.ExcludeExts[strings.ToLower(filepath.Ext(abs))]:
				stamp = append(stamp, row.id)
				excluded++
			default:
				valid = append(valid, item{row, abs})
			}
		}
		// A row that already failed goes alone, before new work: a file
		// that crashes the sidecar can then only take itself down.
		work := valid
		for _, it := range valid {
			if attempts[it.row.id] > 0 {
				work = []item{it}
				break
			}
		}

		results := map[int64]fileDetection{}
		var givenUp []item
		var outage, fatal error
		started := time.Now()
		if len(work) > 0 {
			chunkSize := max(1, min(4, (len(work)+3)/4))
			timeout := max(time.Duration(len(work))*cfg.RequestTimeout, 2*time.Minute)
			var wg sync.WaitGroup
			var mu sync.Mutex
			for start := 0; start < len(work); start += chunkSize {
				chunk := work[start:min(start+chunkSize, len(work))]
				wg.Add(1)
				go func() {
					defer wg.Done()
					paths := make([]string, len(chunk))
					for i, it := range chunk {
						paths[i] = it.abs
					}
					out, err := s.client.DetectBatch(ctx, paths, params, timeout, s.logf)
					mu.Lock()
					defer mu.Unlock()
					if ctx.Err() != nil {
						return
					}
					if err != nil {
						if !isFacesUnavailable(err) {
							s.logf("detect batch failed: %v", err)
						}
						outage = err
						for _, it := range chunk {
							gaveUp, stop := noteFailure(it.row, err, len(chunk) == 1)
							if stop != nil && fatal == nil {
								fatal = stop
							}
							if gaveUp {
								givenUp = append(givenUp, it)
							}
						}
						return
					}
					for i, it := range chunk {
						results[it.row.id] = out[i]
					}
				}()
			}
			wg.Wait()
		}
		if ctx.Err() != nil {
			break
		}
		if err := s.persist(ctx, stamp, results); err != nil {
			return err
		}
		if fatal != nil {
			return fatal
		}
		statSkip += excluded
		statNull += missing + len(givenUp)
		for id, det := range results {
			delete(attempts, id)
			switch {
			case !det.answered:
				statNull++
			case len(det.faces) == 0:
				statEmpty++
			default:
				statFaces += len(det.faces)
				statPhotos++
			}
		}
		done := len(stamp) + len(results) + len(givenUp)
		s.updateScan(false, progress, func(st *facesScanState) { st.Scanned += done })
		if scanned := s.scanState().Scanned; scanned >= nextStatLog {
			s.logf("faces scan progress: %d/%d — %d with faces (%d total), %d no-face, %d errors, %d ext-skipped", scanned, photos+videos, statPhotos, statFaces, statEmpty, statNull, statSkip)
			nextStatLog = scanned + 200
		}
		if outage != nil {
			if err := ensureSidecar(outage.Error()); err != nil {
				return err
			}
		} else if len(results) > 0 && cfg.ThrottleRatio > 0 {
			// Duty cycle: rest in proportion to the time spent detecting.
			pause := min(time.Duration(float64(time.Since(started))*cfg.ThrottleRatio), 5*time.Second)
			if pause >= 10*time.Millisecond {
				sleepCtx(ctx, pause)
			}
		}
	}
	s.logf("faces scan: phase A (photos) done — %d photos had faces (%d total embeddings), %d no-face, %d sidecar errors, %d ext-skipped, %d left for the next scan", statPhotos, statFaces, statEmpty, statNull, statSkip, len(skipped))

	if ctx.Err() != nil || !cfg.ScanVideos || videos == 0 {
		return nil
	}
	// Videos one at a time: each can produce many frames.
	unreadable := 0
	for ctx.Err() == nil {
		rows, err := pick([]string{"video"}, 1)
		if err != nil {
			return err
		}
		if len(rows) == 0 {
			break
		}
		row := rows[0]
		abs := s.app.resolveMedia(row.path)
		if abs == "" {
			if err := s.persist(ctx, []int64{row.id}, nil); err != nil {
				return err
			}
			s.updateScan(false, progress, func(st *facesScanState) { st.Scanned++ })
			continue
		}
		started := time.Now()
		det, err := s.client.DetectVideo(ctx, abs, params, cfg.VideoMaxFrames, s.logf)
		if ctx.Err() != nil {
			break
		}
		if errors.Is(err, errVideoUnreadable) {
			// Left unscanned: a later scan with a path map / shared mount can read it.
			if unreadable == 0 {
				s.logf("faces scan: %v — videos are skipped for this run", err)
			}
			unreadable++
			skipped[row.id] = true
			s.updateScan(false, progress, func(st *facesScanState) { st.Scanned++ })
			continue
		}
		if err != nil {
			if !isFacesUnavailable(err) {
				s.logf("detect video %s failed: %v", abs, err)
			}
			gaveUp, stop := noteFailure(row, err, true)
			if stop != nil {
				return stop
			}
			if gaveUp {
				s.updateScan(false, progress, func(st *facesScanState) { st.Scanned++ })
			}
			if err := ensureSidecar(err.Error()); err != nil {
				return err
			}
			continue
		}
		delete(attempts, row.id)
		if err := s.persist(ctx, nil, map[int64]fileDetection{row.id: det}); err != nil {
			return err
		}
		s.updateScan(false, progress, func(st *facesScanState) { st.Scanned++ })
		if cfg.ThrottleRatio > 0 {
			sleepCtx(ctx, min(time.Duration(float64(time.Since(started))*cfg.ThrottleRatio), 5*time.Second))
		}
	}
	if unreadable > 0 {
		s.logf("faces scan: %d videos could not be read by the sidecar and stay unscanned", unreadable)
	}
	return nil
}

type facesEmbeddings struct {
	data    []float32
	n, dim  int
	ids     []int64
	weights []float64
}

// loadEmbeddings streams every face embedding in id order, keyset-paged.
// Rows whose dimension differs from the first one are skipped.
func (s *facesService) loadEmbeddings(ctx context.Context) (facesEmbeddings, error) {
	var out facesEmbeddings
	var total int
	if err := s.app.db.Reader.QueryRowContext(ctx, `SELECT COUNT(*) FROM faces`).Scan(&total); err != nil {
		return out, err
	}
	out.ids = make([]int64, 0, total)
	out.weights = make([]float64, 0, total)
	skipped := 0
	lastID := int64(-1)
	for out.n < total {
		if err := ctx.Err(); err != nil {
			return out, err
		}
		rows, err := s.app.db.Reader.QueryContext(ctx, `SELECT id, embedding, quality_score FROM faces WHERE id > ? ORDER BY id LIMIT ?`, lastID, facesClusterLoadChunk)
		if err != nil {
			return out, err
		}
		got := 0
		for rows.Next() {
			var id int64
			var blob []byte
			var quality sql.NullFloat64
			if err := rows.Scan(&id, &blob, &quality); err != nil {
				rows.Close()
				return out, err
			}
			got++
			lastID = id
			if out.n >= total {
				continue
			}
			if len(blob) == 0 || len(blob)%4 != 0 {
				skipped++
				continue
			}
			if out.dim == 0 {
				out.dim = len(blob) / 4
				out.data = make([]float32, 0, total*out.dim)
			}
			if len(blob) != out.dim*4 {
				skipped++
				continue
			}
			for i := 0; i < out.dim; i++ {
				out.data = append(out.data, math.Float32frombits(binary.LittleEndian.Uint32(blob[i*4:])))
			}
			out.ids = append(out.ids, id)
			if quality.Valid {
				out.weights = append(out.weights, quality.Float64)
			} else {
				out.weights = append(out.weights, math.NaN())
			}
			out.n++
		}
		rows.Close()
		if err := rows.Err(); err != nil {
			return out, err
		}
		if got == 0 {
			break
		}
	}
	if skipped > 0 {
		s.logf("faces scan: %d face rows skipped (missing / mismatched embedding)", skipped)
	}
	return out, nil
}

func dbscanWorkers() int {
	return max(1, min(runtime.NumCPU()-1, 8))
}

// clusterPhase is Phase B: DBSCAN over every face embedding, then the
// people generation is replaced, carrying labels over.
func (s *facesService) clusterPhase(ctx context.Context, cfg facesSettings, progress func(map[string]any)) error {
	s.logf("faces scan: starting clustering pass")
	emb, err := s.loadEmbeddings(ctx)
	if err != nil {
		if ctx.Err() != nil {
			return nil
		}
		return err
	}
	if emb.n == 0 {
		s.logf("faces scan: no faces detected — clustering skipped")
		return nil
	}
	s.updateScan(true, progress, func(st *facesScanState) { st.Phase, st.FaceCount = "B", emb.n })
	s.logf("faces scan: clustering %d faces (eps=%g, minPts=%g)", emb.n, cfg.Epsilon, cfg.MinPoints)
	started := time.Now()
	result, err := dbscan.Cluster(ctx, emb.data, emb.n, emb.dim, emb.weights, cfg.Epsilon, cfg.MinPoints, dbscanWorkers(), func(done, n int) {
		s.updateScan(false, progress, func(st *facesScanState) {
			st.ClusterProgress = 1
			if n > 0 {
				st.ClusterProgress = float64(done) / float64(n)
			}
		})
	})
	if err != nil {
		if ctx.Err() != nil {
			return nil // cancelled: the previous people are untouched
		}
		return err
	}
	if ctx.Err() != nil {
		return nil
	}
	labels, err := s.labelSnapshot(ctx)
	if err != nil {
		return err
	}
	preserved, err := s.replacePeople(context.WithoutCancel(ctx), result, emb, labels, cfg.LabelMatchEps)
	if err != nil {
		return err
	}
	s.updateScan(true, progress, func(st *facesScanState) {
		st.ClusterProgress, st.PeopleCount, st.NoiseFaces = 1, result.Count, result.NoiseCount
	})
	s.logf("faces scan: clustered %d faces into %d groups in %d s (%d/%d labels preserved across re-cluster, eps=%.3f)", emb.n, result.Count, int(time.Since(started).Seconds()), preserved, len(labels), cfg.LabelMatchEps)
	return nil
}

type labelledCentroid struct {
	label    string
	centroid []float32
}

func decodeEmbedding(blob []byte) []float32 {
	out := make([]float32, len(blob)/4)
	for i := range out {
		out[i] = math.Float32frombits(binary.LittleEndian.Uint32(blob[i*4:]))
	}
	return out
}

// labelSnapshot reads every named person's centroid before the people
// table is replaced.
func (s *facesService) labelSnapshot(ctx context.Context) ([]labelledCentroid, error) {
	rows, err := s.app.db.Reader.QueryContext(ctx, `SELECT label, embedding_centroid FROM people WHERE label IS NOT NULL`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []labelledCentroid
	for rows.Next() {
		var label string
		var blob []byte
		if err := rows.Scan(&label, &blob); err != nil {
			return nil, err
		}
		if len(blob) >= 4 {
			out = append(out, labelledCentroid{label: label, centroid: decodeEmbedding(blob)})
		}
	}
	return out, rows.Err()
}

// carryOverLabel returns the label of the closest snapshot centroid within
// matchEps, or nil.
func carryOverLabel(centroid []float32, snapshot []labelledCentroid, matchEps float64) any {
	var best any
	bestDist := math.Inf(1)
	for _, item := range snapshot {
		if len(item.centroid) != len(centroid) {
			continue
		}
		sum := 0.0
		for i, v := range centroid {
			d := float64(v) - float64(item.centroid[i])
			sum += d * d
		}
		if dist := math.Sqrt(sum); dist < bestDist && dist <= matchEps {
			bestDist, best = dist, item.label
		}
	}
	return best
}

// replacePeople swaps in the new people generation: new rows first, faces
// re-pointed in bounded transactions, then the previous generation and any
// face still pointing at it (noise this time) cleared.
func (s *facesService) replacePeople(ctx context.Context, result dbscan.Result, emb facesEmbeddings, snapshot []labelledCentroid, matchEps float64) (int, error) {
	db := s.app.db.Writer
	var oldMax int64
	if err := db.QueryRowContext(ctx, `SELECT COALESCE(MAX(id), 0) FROM people`).Scan(&oldMax); err != nil {
		return 0, err
	}
	personIDs := make([]int64, result.Count)
	preserved := 0
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return 0, err
	}
	now := nowMillis()
	for c := 0; c < result.Count; c++ {
		centroid := result.Centroids[c*emb.dim : (c+1)*emb.dim]
		label := carryOverLabel(centroid, snapshot, matchEps)
		if label != nil {
			preserved++
		}
		faceCount := result.Starts[c+1] - result.Starts[c]
		res, err := tx.Exec(`INSERT INTO people (label, embedding_centroid, face_count, created_at, updated_at) VALUES (?, ?, ?, ?, ?)`, label, embeddingBlob(centroid), faceCount, now, now)
		if err != nil {
			_ = tx.Rollback()
			return 0, err
		}
		if personIDs[c], err = res.LastInsertId(); err != nil {
			_ = tx.Rollback()
			return 0, err
		}
	}
	if err := tx.Commit(); err != nil {
		return 0, err
	}
	written := 0
	tx, err = db.BeginTx(ctx, nil)
	if err != nil {
		return 0, err
	}
	for c := 0; c < result.Count; c++ {
		for _, member := range result.Members[result.Starts[c]:result.Starts[c+1]] {
			if _, err := tx.Exec(`UPDATE faces SET person_id = ? WHERE id = ?`, personIDs[c], emb.ids[member]); err != nil {
				_ = tx.Rollback()
				return 0, err
			}
			if written++; written%facesClusterWrite == 0 {
				if err := tx.Commit(); err != nil {
					return 0, err
				}
				if tx, err = db.BeginTx(ctx, nil); err != nil {
					return 0, err
				}
			}
		}
	}
	if _, err := tx.Exec(`UPDATE faces SET person_id = NULL WHERE person_id <= ?`, oldMax); err != nil {
		_ = tx.Rollback()
		return 0, err
	}
	if _, err := tx.Exec(`DELETE FROM people WHERE id <= ?`, oldMax); err != nil {
		_ = tx.Rollback()
		return 0, err
	}
	return preserved, tx.Commit()
}

// qualityFilter drops detections the cluster pass should not see
// (faces.js qualityFilter): low score, small box, non-square aspect.
func qualityFilter(faces []detectedFace, cfg facesSettings) []detectedFace {
	out := faces[:0:0]
	for _, f := range faces {
		if f.Score < cfg.MinScore || math.Min(f.W, f.H) < float64(cfg.MinBoxPx) || f.W <= 0 || f.H <= 0 {
			continue
		}
		if ratio := f.W / f.H; ratio < 0.5 || ratio > 2.0 {
			continue
		}
		out = append(out, f)
	}
	return out
}

// ---- Per-download hook and auto-scan (src/core/ai/index.js) -------------

// enqueue queues a finished download for background face detection.
// Live downloads jump ahead of history backfill; full queues drop the id
// (a scan reconciles). It never blocks the downloader.
func (s *facesService) enqueue(id int64, realtime bool) {
	s.queueMu.Lock()
	queue := &s.backfill
	if realtime {
		queue = &s.realtime
	}
	if len(*queue) < facesQueueCap {
		*queue = append(*queue, id)
	}
	s.queueMu.Unlock()
	select {
	case s.wake <- struct{}{}:
	default:
	}
}

func (s *facesService) queueDepths() (int, int) {
	s.queueMu.Lock()
	defer s.queueMu.Unlock()
	return len(s.realtime), len(s.backfill)
}

func (s *facesService) next() (int64, bool) {
	s.queueMu.Lock()
	defer s.queueMu.Unlock()
	for _, queue := range []*[]int64{&s.realtime, &s.backfill} {
		if len(*queue) > 0 {
			id := (*queue)[0]
			*queue = (*queue)[1:]
			return id, true
		}
	}
	return 0, false
}

func (s *facesService) clearQueues() {
	s.queueMu.Lock()
	s.realtime, s.backfill = nil, nil
	s.queueMu.Unlock()
}

// configChanged wakes the auto-scan loop after an advanced.ai save.
func (s *facesService) configChanged() {
	select {
	case s.configWake <- struct{}{}:
	default:
	}
}

// run owns the background queue and the auto-scan drip timer.
func (s *facesService) run(ctx context.Context) {
	timer := time.NewTimer(5 * time.Second)
	defer timer.Stop()
	for ctx.Err() == nil {
		tick := false
		select {
		case <-ctx.Done():
			return
		case <-s.wake:
		case <-s.configWake:
			tick = true
		case <-timer.C:
			tick = true
		}
		if tick {
			interval := s.autoScanTick(ctx)
			if !timer.Stop() {
				select {
				case <-timer.C:
				default:
				}
			}
			timer.Reset(interval)
		}
		s.drain(ctx)
	}
}

// autoScanTick pushes a batch of unscanned rows onto the backfill queue
// when advanced.ai.autoScan is "running" and returns the next interval.
func (s *facesService) autoScanTick(ctx context.Context) time.Duration {
	cfg, err := s.app.facesSettings(ctx)
	if err != nil || !cfg.Enabled || cfg.AutoScan != "running" {
		return time.Minute
	}
	realtime, backfill := s.queueDepths()
	if backfill >= cfg.AutoScanCeiling || realtime > 0 || s.scanRunning() {
		return cfg.AutoScanInterval
	}
	rows, err := s.unindexed(ctx, cfg.statusTypes(), cfg.AutoScanBatch)
	if err != nil {
		s.logf("auto-scan tick failed: %v", err)
		return cfg.AutoScanInterval
	}
	for _, row := range rows {
		s.enqueue(row.id, false)
	}
	if len(rows) > 0 {
		s.logf("auto-scan tick: enqueued=%d backfillDepth=%d ceiling=%d", len(rows), backfill, cfg.AutoScanCeiling)
	}
	return cfg.AutoScanInterval
}

// drain detects faces for queued downloads, one at a time.
func (s *facesService) drain(ctx context.Context) {
	if _, ok := s.peek(); !ok {
		return
	}
	cfg, err := s.settings(ctx)
	// Stamping rows while face clustering is off would hide them from the
	// scan once it is turned on.
	if err != nil || !cfg.Enabled || !cfg.FaceClustering || cfg.URL == "" {
		s.clearQueues()
		return
	}
	types := map[string]bool{}
	for _, t := range cfg.BackgroundTypes {
		types[t] = true
	}
	for ctx.Err() == nil {
		if s.scanRunning() {
			s.clearQueues() // the running scan picks these rows up
			return
		}
		id, ok := s.next()
		if !ok {
			return
		}
		var stored, fileType sql.NullString
		var indexed sql.NullInt64
		if err := s.app.db.Reader.QueryRowContext(ctx, `SELECT file_path, file_type, ai_indexed_at FROM downloads WHERE id = ?`, id).Scan(&stored, &fileType, &indexed); err != nil {
			continue
		}
		if indexed.Valid || !types[strings.ToLower(fileType.String)] || strings.HasSuffix(stored.String, ".part") {
			continue
		}
		abs := s.app.resolveMedia(stored.String)
		result := map[int64]fileDetection{}
		if abs != "" {
			out, err := s.client.DetectBatch(ctx, []string{abs}, cfg.detectParams(), 0, s.logf)
			if ctx.Err() != nil {
				return
			}
			if err != nil {
				if isFacesUnavailable(err) {
					// Leave this and everything queued unstamped for a later scan.
					s.clearQueues()
					return
				}
				s.logf("background detect %s failed: %v", abs, err)
			} else {
				det := out[0]
				det.faces = qualityFilter(det.faces, cfg)
				result[id] = det
			}
		}
		stamp := []int64{id}
		if _, ok := result[id]; ok {
			stamp = nil
		}
		if err := s.persist(ctx, stamp, result); err != nil {
			s.logf("background detect: db write skipped for download %d: %v", id, err)
		}
	}
}

func (s *facesService) peek() (int64, bool) {
	s.queueMu.Lock()
	defer s.queueMu.Unlock()
	if len(s.realtime) > 0 {
		return s.realtime[0], true
	}
	if len(s.backfill) > 0 {
		return s.backfill[0], true
	}
	return 0, false
}

// ---- Quality backfill (server.js /api/ai/backfill-quality) ---------------

// qualityBackfill re-detects downloads whose faces lack quality_score and
// copies the score of the best-overlapping detection (IoU > 0.3).
func (s *facesService) qualityBackfill(ctx context.Context, progress func(map[string]any)) (map[string]any, error) {
	rows, err := s.app.db.Reader.QueryContext(ctx, `SELECT DISTINCT download_id FROM faces WHERE quality_score IS NULL ORDER BY download_id`)
	if err != nil {
		return nil, err
	}
	var ids []int64
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return nil, err
		}
		ids = append(ids, id)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}
	processed, updated, failed, total := 0, 0, 0, len(ids)
	defaults := facesDetectParams{MinScore: facesDefaultMinScore, MinBoxPx: facesDefaultMinBoxPx, ARRange: [2]float64{0.5, 2.0}}
	for _, id := range ids {
		if ctx.Err() != nil {
			break
		}
		var stored sql.NullString
		_ = s.app.db.Reader.QueryRowContext(ctx, `SELECT file_path FROM downloads WHERE id = ?`, id).Scan(&stored)
		abs := s.app.resolveMedia(stored.String)
		switch {
		case !stored.Valid || stored.String == "":
		case abs == "":
			failed++
		default:
			out, err := s.client.DetectBatch(ctx, []string{abs}, defaults, 0, s.logf)
			if err != nil {
				if ctx.Err() == nil && isFacesUnavailable(err) {
					return nil, err
				}
				break
			}
			n, err := s.applyQuality(ctx, id, out[0].faces)
			if err != nil {
				return nil, err
			}
			updated += n
		}
		processed++
		if processed%20 == 0 || processed == total {
			progress(map[string]any{"processed": processed, "total": total, "updated": updated, "errors": failed})
		}
	}
	return map[string]any{"processed": processed, "total": total, "updated": updated, "errors": failed}, nil
}

func (s *facesService) applyQuality(ctx context.Context, downloadID int64, detected []detectedFace) (int, error) {
	if len(detected) == 0 {
		return 0, nil
	}
	rows, err := s.app.db.Reader.QueryContext(ctx, `SELECT id, x, y, w, h FROM faces WHERE download_id = ? AND quality_score IS NULL`, downloadID)
	if err != nil {
		return 0, err
	}
	type box struct {
		id         int64
		x, y, w, h float64
	}
	var stored []box
	for rows.Next() {
		var b box
		if err := rows.Scan(&b.id, &b.x, &b.y, &b.w, &b.h); err != nil {
			rows.Close()
			return 0, err
		}
		stored = append(stored, b)
	}
	rows.Close()
	updated := 0
	for _, sf := range stored {
		bestIoU := 0.0
		var bestQ any
		for _, d := range detected {
			iw := math.Max(0, math.Min(sf.x+sf.w, d.X+d.W)-math.Max(sf.x, d.X))
			ih := math.Max(0, math.Min(sf.y+sf.h, d.Y+d.H)-math.Max(sf.y, d.Y))
			inter := iw * ih
			union := sf.w*sf.h + d.W*d.H - inter
			iou := 0.0
			if union > 0 {
				iou = inter / union
			}
			if iou > bestIoU && iou > 0.3 {
				bestIoU, bestQ = iou, d.storedQuality()
			}
		}
		if bestQ != nil {
			if _, err := s.app.db.Writer.ExecContext(context.WithoutCancel(ctx), `UPDATE faces SET quality_score = ? WHERE id = ?`, bestQ, sf.id); err != nil {
				return updated, err
			}
			updated++
		}
	}
	return updated, nil
}

