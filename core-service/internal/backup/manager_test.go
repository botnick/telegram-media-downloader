// An edit may arrive after a worker claimed the old message's backup. The
// completed old transfer must not erase the new request in that same job row.
type editDuringUpload struct {
	Provider
	edit  func()
	calls int
}

func (p *editDuringUpload) Upload(ctx context.Context, name string, src io.ReadSeeker, size int64, progress func(int64)) (UploadResult, error) {
	p.calls++
	result, err := p.Provider.Upload(ctx, name, src, size, progress)
	if p.calls == 1 {
		p.edit()
	}
	return result, err
}
func TestEditedMediaDuringUploadKeepsNewRevisionPending(t *testing.T) {
	var edit func()
	m, db, dir := fixtureManager(t, func(ctx context.Context, name string, cfg map[string]any) (Provider, error) {
		p, e := nativeProvider(ctx, name, cfg)
		return &editDuringUpload{Provider: p, edit: func() { edit() }}, e
	})
	target := filepath.Join(dir, "target")
	id := addLocal(t, m, target, "mirror")
	if err := m.Pause(context.Background(), id, true); err != nil {
		t.Fatal(err)
	}
	row := addSource(t, db, dir, "old.bin", "old contents", 1)
	if err := os.WriteFile(filepath.Join(dir, "downloads/new.bin"), []byte("new contents"), 0600); err != nil {
		t.Fatal(err)
	}
	edits := make(chan error, 1)
	edit = func() {
		_, err := db.Writer.Exec(`UPDATE downloads SET file_path='new.bin',file_hash='new-hash' WHERE id=?`, row)
		edits <- err
	}
	if err := m.Pause(context.Background(), id, false); err != nil {
		t.Fatal(err)
	}
	waitBackup(t, m, id, 1, 0)
	if err := <-edits; err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(target, "new.bin"))
	if err != nil || string(b) != "new contents" {
		t.Fatalf("edited media lost: %q %v", b, err)
	}
	jobs, _ := m.Jobs(context.Background(), id, "", 50, 0, false)
	if len(jobs) != 1 || jobs[0]["remote_path"] != "new.bin" {
		t.Fatalf("revision replaced job unexpectedly: %v", jobs)
	}
}
