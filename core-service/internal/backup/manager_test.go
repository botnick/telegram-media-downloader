type failureProvider struct {
	Provider
	calls   atomic.Int64
	started chan struct{}
	block   bool
}

func (p *failureProvider) Upload(ctx context.Context, name string, r io.ReadSeeker, size int64, progress func(int64)) (UploadResult, error) {
	n := p.calls.Add(1)
	if p.block {
		if n == 1 {
			close(p.started)
		}
		<-ctx.Done()
		return UploadResult{}, ctx.Err()
	}
	if n == 1 {
		return UploadResult{}, errors.New("transient upload error")
	}
	return p.Provider.Upload(ctx, name, r, size, progress)
}
