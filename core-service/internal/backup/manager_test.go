func addSource(t *testing.T, db *store.DB, dir, name, content string, msg int) int64 {
	t.Helper()
	file := filepath.Join(dir, "downloads", name)
	if err := os.MkdirAll(filepath.Dir(file), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(file, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
	r, err := db.Writer.Exec(`INSERT INTO downloads(group_id,message_id,file_name,file_path,file_size) VALUES('fixture',?,?,?,?)`, msg, filepath.Base(name), name, len(content))
	if err != nil {
		t.Fatal(err)
	}
	id, err := r.LastInsertId()
	if err != nil {
		t.Fatal(err)
	}
	return id
}
func waitBackup(t *testing.T, m *Manager, id int64, done, failed int64) {
	t.Helper()
	deadline := time.Now().Add(7 * time.Second)
	for time.Now().Before(deadline) {
		s, err := m.Status(context.Background(), id)
		if err == nil && s["completed24h"] == done && s["failed24h"] == failed && s["queued"] == int64(0) && s["processing"] == int64(0) && s["running"] == false {
			return
		}
		time.Sleep(10 * time.Millisecond)
	}
	s, e := m.Status(context.Background(), id)
	t.Fatalf("backup did not finish: %v %v", s, e)
}
func TestCredentialsMatchIndependentTGDCVectorAndRejectTampering(t *testing.T) {
	// Independently generated by Python cryptography AESGCM + hashlib.pbkdf2_hmac.
	blob, _ := hex.DecodeString("5447444301000102030405060708090a0bbc0c1a2f9971f233f07fb7ed7a700b234dbcee61632cbc2996846523de807048539534c5cda1385732a51409904b85a99b57d3a2e499bc79789cf4d519c73e759cf8")
	secret := bytes.Repeat([]byte{0x11}, 32)
	cfg, err := openConfig(blob, secret)
	if err != nil || cfg["password"] != "test-only" || cfg["rootPath"] != "/fixture/nas" {
		t.Fatalf("legacy vector: %v %v", cfg, err)
	}
	sealed, err := sealConfig(cfg, secret)
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Contains(sealed, []byte("test-only")) {
		t.Fatal("plaintext credential")
	}
	if _, err = openConfig(sealed, secret); err != nil {
		t.Fatal(err)
	}
	for _, i := range []int{0, 4, 5, 17, len(sealed) - 1} {
		bad := append([]byte(nil), sealed...)
		bad[i] ^= 1
		if _, err = openConfig(bad, secret); err == nil {
			t.Fatalf("tampered byte %d accepted", i)
		}
	}
	if _, err = openConfig(sealed, bytes.Repeat([]byte{0x22}, 32)); err == nil {
		t.Fatal("wrong secret accepted")
	}
}
