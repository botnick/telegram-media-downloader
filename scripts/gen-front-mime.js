#!/usr/bin/env node
/**
 * Generate core-service/internal/front/mime_table.go from the MIME table
 * Express's res.sendFile / express.static use (the `mime` 1.x copy that
 * `send` bundles), so tgdl-core's front server answers with exactly the
 * Content-Type Node would.
 *
 *   node scripts/gen-front-mime.js          write the file
 *   node scripts/gen-front-mime.js --check  exit 1 when it is out of date
 *
 * tests/front-mime.test.js runs the check, so a dependency bump that
 * changes the table fails CI until the file is regenerated.
 */

import fs from 'fs';
import { createRequire } from 'module';
import path from 'path';

const require = createRequire(import.meta.url);
const REPO = path.resolve(import.meta.dirname, '..');
const OUT = path.join(REPO, 'core-service', 'internal', 'front', 'mime_table.go');

export function sendMimeTypes() {
    const send = require('send');
    return { types: { ...send.mime.types }, defaultType: send.mime.default_type };
}

export function render() {
    const { types, defaultType } = sendMimeTypes();
    const exts = Object.keys(types).sort();
    // One "ext type" pair per line inside a raw string: gofmt leaves it
    // alone, so the generated file is formatted without running Go.
    const lines = exts.map((e) => {
        const line = `${e} ${types[e]}`;
        if (/[\s`]/.test(e) || /[\s`]/.test(types[e])) throw new Error(`unexpected: ${line}`);
        return line;
    });
    return `// Code generated by scripts/gen-front-mime.js; DO NOT EDIT.
//
// Extension -> type map of the mime 1.x package bundled with send (what
// Express's res.sendFile and express.static use), one "ext type" pair per
// line.

package front

const defaultMimeType = ${JSON.stringify(defaultType)}

const mimeData = \`${lines.join('\n')}
\`
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
    const text = render();
    if (process.argv.includes('--check')) {
        const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
        if (cur !== text) {
            console.error(
                `${path.relative(REPO, OUT)} is out of date: run node scripts/gen-front-mime.js`,
            );
            process.exit(1);
        }
        console.log('mime table up to date');
    } else {
        fs.mkdirSync(path.dirname(OUT), { recursive: true });
        fs.writeFileSync(OUT, text);
        console.log(`wrote ${path.relative(REPO, OUT)}`);
    }
}
