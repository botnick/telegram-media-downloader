#!/usr/bin/env node
// Regenerate tests/contract/inventory.json from the live sources: every
// HTTP route in src/web/server.js and every WebSocket message type the
// backend broadcasts. Hand-written `skip` reasons on existing entries are
// kept; new entries start without one (so the checker demands coverage).
//
// Usage: node scripts/contract-inventory.mjs [--check]

import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'tests', 'contract', 'inventory.json');
const { buildInventory } = await import(
    pathToFileURL(path.join(REPO, 'tests', 'contract', 'lib', 'inventory.js')).href
);

export function mergedInventory() {
    const fresh = buildInventory(REPO);
    const old = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : {};
    const skipOf = (list, key) => new Map((list || []).map((e) => [e[key], e.skip]));
    const routeSkips = skipOf(old.routes, 'key');
    const wsSkips = skipOf(old.wsEvents, 'type');
    const clusterSkips = skipOf(old.clusterWs?.events, 'key');
    const withSkip = (e, skip) => (skip ? { ...e, skip } : e);
    const clusterEvents = [
        ...fresh.clusterWs.sent.map((t) => ({ key: `send ${t}`, direction: 'send', type: t })),
        ...fresh.clusterWs.accepted.map((t) => ({
            key: `accept ${t}`,
            direction: 'accept',
            type: t,
        })),
    ];
    return {
        $comment:
            'Generated by scripts/contract-inventory.mjs — edit only the `skip` reasons. ' +
            'tests/contract/inventory.contract.test.js fails when this file is stale or when an ' +
            'entry is neither covered by a golden snapshot nor skipped with a reason.',
        routes: fresh.routes.map((r) => withSkip(r, routeSkips.get(r.key))),
        wsEvents: fresh.wsEvents.map((e) => withSkip(e, wsSkips.get(e.type))),
        clusterWs: {
            events: clusterEvents.map((e) => withSkip(e, clusterSkips.get(e.key))),
        },
        unresolved: fresh.unresolved,
    };
}

export function serialize(inv) {
    return `${JSON.stringify(inv, null, 2)}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
    const inv = mergedInventory();
    const text = serialize(inv);
    if (process.argv.includes('--check')) {
        const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
        if (cur !== text) {
            console.error(
                'tests/contract/inventory.json is stale — run: npm run contract:inventory',
            );
            process.exit(1);
        }
        console.log('inventory.json up to date');
    } else {
        fs.writeFileSync(OUT, text);
        console.log(
            `wrote ${path.relative(REPO, OUT)}: ${inv.routes.length} routes, ${inv.wsEvents.length} WS events, ${inv.clusterWs.events.length} cluster WS entries`,
        );
        if (inv.unresolved.length) {
            console.error('unresolved dynamic broadcast sites:', inv.unresolved);
            process.exit(1);
        }
    }
}
